// One-command local setup: writes n8n/.env (gitignored, mode 0600) and mirrors
// the shared values into the Convex deployment. Never prints a secret value.
// Named setup:local because `pnpm setup` is a pnpm built-in (it edits shell config).
//   pnpm setup:local            create missing values, keep existing ones
//   pnpm setup:local --rotate   rotate both HMAC secrets, keeping the old ones as *_PREVIOUS
// A rotation never breaks deliveries: each verifier learns the new secret
// before its signer starts using it (order in scripts/lib/rotation.ts).
import bcrypt from "bcryptjs";
import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { createServer } from "node:net";
import { relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parseEnv, randomSecret, serializeEnv } from "./lib/envfile";
import { rotationPlan } from "./lib/rotation";

const ENV_PATH = fileURLToPath(new URL("../n8n/.env", import.meta.url));
const ROOT = fileURLToPath(new URL("..", import.meta.url));
const COMPOSE = ["compose", "--env-file", "n8n/.env"];
const N8N_WEBHOOK = "http://localhost:5678/webhook/lendloop-loan-events";
const HEADER = "# Generated by pnpm setup:local. Local secrets: never commit.";
const HASH_KEY = "N8N_INSTANCE_OWNER_PASSWORD_HASH";
// n8n env name -> Convex env name.
const HMAC_KEYS = [
  ["LENDLOOP_N8N_WEBHOOK_SECRET", "N8N_WEBHOOK_SECRET"],
  ["LENDLOOP_CONVEX_INBOUND_SECRET", "CONVEX_INBOUND_SECRET"],
] as const;
const DEFAULTS: [string, string][] = [
  ["N8N_INSTANCE_OWNER_EMAIL", "owner@lendloop.local"],
  ["N8N_INSTANCE_OWNER_FIRST_NAME", "LendLoop"],
  ["N8N_INSTANCE_OWNER_LAST_NAME", "Owner"],
  ["GENERIC_TIMEZONE", "UTC"],
  ["CONVEX_SITE_URL", "http://host.docker.internal:3211"],
  ["MAIL_FROM", "LendLoop <no-reply@lendloop.local>"],
  ["OPS_EMAIL", "ops@lendloop.local"],
  ["MAIL_API_URL", "http://mail-api:8080"],
];
// Keys earlier versions wrote (n8n used to send over SMTP); removed on the next run.
const OBSOLETE = ["SMTP_HOST", "SMTP_PORT", "SMTP_USER", "SMTP_PASS", "SMTP_SECURE"];

// docker compose interpolates "$" in env files, so the bcrypt hash is stored with "$$".
const escapeDollars = (value: string) => value.replaceAll("$", () => "$$");
const unescapeDollars = (value: string) => value.replaceAll("$$", () => "$");

function portIsFree(port: number): Promise<boolean> {
  return new Promise((resolve) => {
    const server = createServer();
    server.once("error", () => resolve(false));
    server.listen(port, () => server.close(() => resolve(true)));
  });
}

// Values go through stdin, never argv; the CLI only reports counts.
function pushToConvex(values: Map<string, string>): boolean {
  const result = spawnSync("pnpm", ["exec", "convex", "env", "set", "--force"], {
    input: serializeEnv(values),
    stdio: ["pipe", "ignore", "inherit"],
  });
  return result.status === 0;
}

function n8nIsRunning(): boolean {
  const result = spawnSync("docker", [...COMPOSE, "ps", "--status", "running", "--services"], {
    cwd: ROOT,
    encoding: "utf8",
  });
  return result.status === 0 && result.stdout.split("\n").includes("n8n");
}

// Recreates the n8n container with the new n8n/.env and waits until it is
// healthy with its workflows published: the entrypoint publishes all of them
// before `n8n start`, so a 401 (not a 404) to an unsigned webhook call means
// the whole set is live.
async function restartN8n(): Promise<boolean> {
  const up = spawnSync("docker", [...COMPOSE, "up", "-d", "n8n"], { cwd: ROOT, stdio: ["ignore", "ignore", "inherit"] });
  if (up.status !== 0) return false;
  const deadline = Date.now() + 180_000;
  while (Date.now() < deadline) {
    const status = await fetch(N8N_WEBHOOK, { method: "POST", body: "{}" }).then(
      (r) => r.status,
      () => 0,
    );
    if (status === 401) return true;
    await new Promise((resolve) => setTimeout(resolve, 2000));
  }
  return false;
}

async function main() {
  const rotate = process.argv.includes("--rotate");
  const before = existsSync(ENV_PATH) ? readFileSync(ENV_PATH, "utf8") : "";
  const env = parseEnv(before);
  const created: string[] = [];
  const rotated: string[] = [];
  const ensure = (key: string, make: () => string) => {
    if (env.get(key)) return;
    env.set(key, make());
    created.push(key);
  };

  ensure("N8N_ENCRYPTION_KEY", () => randomSecret());
  ensure("POSTGRES_PASSWORD", () => randomSecret());
  for (const [key] of HMAC_KEYS) {
    const current = env.get(key);
    if (rotate && current) {
      env.set(`${key}_PREVIOUS`, current);
      env.set(key, randomSecret());
      rotated.push(key);
    } else {
      ensure(key, () => randomSecret());
    }
  }
  ensure("MAIL_API_KEY", () => randomSecret());
  ensure("N8N_OWNER_PASSWORD", () => randomBytes(24).toString("base64url"));
  for (const key of OBSOLETE) {
    if (env.delete(key)) created.push(`${key} (removed)`);
  }
  for (const [key, value] of DEFAULTS) {
    if (env.has(key)) continue;
    env.set(key, value);
    created.push(key);
  }
  if (!env.has("MAILPIT_UI_PORT")) {
    let port = 8025;
    while (port < 8035 && !(await portIsFree(port))) port++;
    env.set("MAILPIT_UI_PORT", String(port));
    created.push("MAILPIT_UI_PORT");
  }

  // Re-hash only when the stored hash no longer matches the password.
  const password = env.get("N8N_OWNER_PASSWORD")!;
  const storedHash = unescapeDollars(env.get(HASH_KEY) ?? "");
  if (!storedHash || !bcrypt.compareSync(password, storedHash)) {
    env.set(HASH_KEY, escapeDollars(bcrypt.hashSync(password, 10)));
    created.push(HASH_KEY);
  }

  const next = serializeEnv(env, HEADER);
  if (next !== before) writeFileSync(ENV_PATH, next, { mode: 0o600 });
  chmodSync(ENV_PATH, 0o600);

  const convexEnv = new Map<string, string>([
    ["N8N_WEBHOOK_URL", "http://localhost:5678/webhook/lendloop-loan-events"],
    ["APP_URL", "http://localhost:3000"],
    ["APP_TIMEZONE", env.get("GENERIC_TIMEZONE") || "UTC"],
  ]);
  for (const [n8nKey, convexKey] of HMAC_KEYS) {
    convexEnv.set(convexKey, env.get(n8nKey)!);
    const previous = env.get(`${n8nKey}_PREVIOUS`);
    if (previous) convexEnv.set(`${convexKey}_PREVIOUS`, previous);
  }
  // n8n/.env is already written; Convex is updated last (around an n8n restart).
  const webhookSecretRotated = rotated.includes("LENDLOOP_N8N_WEBHOOK_SECRET");
  const n8nRunning = webhookSecretRotated && n8nIsRunning();
  const plan = rotationPlan(convexEnv, {
    webhookSecretRotated,
    oldWebhookSecret: env.get("LENDLOOP_N8N_WEBHOOK_SECRET_PREVIOUS"),
    n8nRunning,
  });
  let pushed = true;
  for (const step of plan) {
    if (step.kind === "convex") {
      pushed = pushToConvex(step.values);
      if (!pushed) break;
      continue;
    }
    console.log("Convex accepts the new n8n->Convex secret; restarting n8n with the new secrets...");
    if (!(await restartN8n())) {
      console.error(
        "n8n did not come back with its workflows published within 3 minutes. Convex still signs with the" +
          " previous secret, which n8n accepts: fix n8n (`pnpm stack:up`), then run `pnpm setup:local` to finish.",
      );
      process.exit(1);
    }
    console.log("n8n is healthy and accepts both webhook secrets; switching Convex to the new one.");
  }

  const file = relative(process.cwd(), ENV_PATH);
  if (created.length) console.log(`Created or updated: ${created.join(", ")}`);
  if (rotated.length) console.log(`Rotated (old values kept as *_PREVIOUS): ${rotated.join(", ")}`);
  if (!created.length && !rotated.length) console.log("No changes to n8n/.env");
  console.log(`n8n owner: ${env.get("N8N_INSTANCE_OWNER_EMAIL")} (password: N8N_OWNER_PASSWORD in ${file})`);
  console.log(`Mailpit UI: http://localhost:${env.get("MAILPIT_UI_PORT")}`);
  if (!pushed) {
    console.error("Could not update the Convex deployment. Start it with `pnpm dev:convex` and rerun `pnpm setup:local`.");
    process.exit(1);
  }
  if (webhookSecretRotated && !n8nRunning) {
    console.log(
      "n8n is not running. Start it (`pnpm stack:up`) before anything else: it then holds the new secrets and still" +
        " accepts the previous ones. Until it is up, Convex deliveries wait in the outbox and retry.",
    );
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : "setup failed");
  process.exit(1);
});
